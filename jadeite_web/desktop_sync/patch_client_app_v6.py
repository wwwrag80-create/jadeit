# -*- coding: utf-8 -*-
"""
الدفعة السادسة: إعادة تسمية شاملة وآمنة

    الفاقد الكلي   ←  ذهب/باقي
    الفاقد الزائد  ←  ذهب/صافي

التسمية تُغيَّر في **كل** مكان: مفاتيح الحسابات الداخلية، عناوين الأعمدة،
الطباعة، والتقارير — حتى لا يبقى اسم قديم مرتبط بعملية فيتعطّل الحساب.

ملاحظة أمان: هذه المفاتيح داخلية في الذاكرة فقط (قاموس ledger)،
ولا تُخزَّن في قاعدة البيانات ولا تُقارن بقيم محفوظة، فتغييرها آمن تماماً
ما دام يشمل كل المواضع — وهذا ما يتحقق منه السكربت قبل الحفظ.

الاستخدام:  python3 patch_client_app_v6.py rageh-1-34-14-cloud.py
"""
import io
import re
import sys

SRC = sys.argv[1] if len(sys.argv) > 1 else "rageh-1-34-14-cloud.py"
src = io.open(SRC, encoding="utf-8").read()

OLD_TOTAL, NEW_TOTAL = "الفاقد الكلي", "ذهب/باقي"
OLD_NET, NEW_NET = "الفاقد الزائد", "ذهب/صافي"

before_total = src.count(OLD_TOTAL)
before_net = src.count(OLD_NET)
print(f"المواضع الموجودة: {OLD_TOTAL} = {before_total} | {OLD_NET} = {before_net}")

# ---------------------------------------------------------------- الاستبدال
src = src.replace(OLD_TOTAL, NEW_TOTAL)
src = src.replace(OLD_NET, NEW_NET)

# ---------------------------------------------------------------- تصحيح الشروح
# بعض الجمل التوضيحية تصبح ركيكة بعد الاستبدال الحرفي
src = src.replace(
    "إجمالي (ذهب/صافي) لكل عمال القسم — وهو ما يظهر أسفل الجدول",
    "إجمالي عمود (ذهب/صافي) لكل عمال القسم — وهو ما يظهر أسفل الجدول")
src = src.replace(
    "= إجمالي ذهب/صافي، ناقص ما سبق إقفاله.",
    "= إجمالي عمود (ذهب/صافي)، ناقص ما سبق إقفاله.")
src = src.replace(
    "# لوحة (الذهب عند القسم) = إجمالي ذهب/صافي، ويصبح صفراً بعد الإقفال",
    "# لوحة (الذهب عند القسم) = إجمالي عمود (ذهب/صافي)، ويصبح صفراً بعد الإقفال")

# ---------------------------------------------------------------- التحقق
assert OLD_TOTAL not in src, "بقيت مواضع باسم قديم: " + OLD_TOTAL
assert OLD_NET not in src, "بقيت مواضع باسم قديم: " + OLD_NET
assert src.count(NEW_TOTAL) == before_total, "عدد المواضع تغيّر بعد الاستبدال!"
assert src.count(NEW_NET) == before_net, "عدد المواضع تغيّر بعد الاستبدال!"

import ast
ast.parse(src)

io.open(SRC, "w", encoding="utf-8").write(src)
print(f"✔ تم استبدال {before_total + before_net} موضعاً بالكامل")
print(f"✔ {NEW_TOTAL} و {NEW_NET} مطبّقان في المفاتيح والأعمدة والطباعة والتقارير")
